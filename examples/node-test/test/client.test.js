'use strict';

// The app's controllers, through the whole stack: npm package, wire protocol,
// SQL, and Prisma Client. Each test file gets a database of its own from the
// baked image, which costs about a millisecond.

const assert = require('node:assert/strict');
const { after, before, describe, it } = require('node:test');

const { authors, posts, startDatabase } = require('@mysql-ultralight-example/app');

let database;
before(async () => {
    database = await startDatabase();
});
after(async () => {
    await database?.stop();
});

const db = () => database.db;

describe('reads', () => {
    it('follows relations in both directions', async () => {
        const ada = await authors.byEmail(db(), 'ada@example.com');
        assert.equal(ada.name, 'Ada Lovelace');

        const counts = await authors.withPostCounts(db());
        assert.deepEqual(
            counts.map((a) => [a.name, a.posts]),
            [
                ['Ada Lovelace', 1],
                ['Grace Hopper', 1]
            ]
        );
    });

    it('groups and orders', async () => {
        const tags = await posts.tagCounts(db());
        assert.deepEqual(
            tags.map((t) => t.name),
            ['engineering', 'history', 'release-notes']
        );
        assert.equal(tags[0].posts, 1);
    });
});

describe('writes', () => {
    it('creates a graph in one call', async () => {
        const created = await authors.register(db(), {
            email: 'alan@example.com',
            name: 'Alan Turing',
            role: 'EDITOR',
            website: 'https://example.com'
        });

        // A cuid, generated by Prisma rather than supplied by the test.
        assert.match(created.id, /^c[a-z0-9]+$/);
        assert.equal(created.profile.website, 'https://example.com');
    });

    it('rolls a transaction back', async () => {
        const before = await db().author.count();

        let written = null;
        await assert.rejects(
            () =>
                db().$transaction(async (tx) => {
                    // Held onto so the test can prove the row existed inside
                    // the transaction: without it, everything below passes
                    // against an engine that wrote nothing at all.
                    written = await tx.author.create({
                        data: { email: 'rolled@example.com', name: 'Rolled Back' }
                    });
                    assert.ok(written.id);
                    assert.equal(await tx.author.count(), before + 1);

                    await tx.author.create({
                        data: { email: 'ada@example.com', name: 'Clash' }
                    });
                }),
            /Unique constraint failed/
        );

        assert.ok(written, 'the first insert never ran, so nothing was rolled back');
        assert.equal(await db().author.count(), before);
    });

    it('enforces the constraints the schema declares', async () => {
        const ada = await authors.byEmail(db(), 'ada@example.com');

        // The compound unique on (authorId, slug).
        await assert.rejects(
            () =>
                db().post.create({
                    data: {
                        authorId: ada.id,
                        title: 'Duplicate',
                        slug: 'on-the-analytical-engine'
                    }
                }),
            /Unique constraint failed/
        );

        // The foreign key on Post.authorId.
        await assert.rejects(
            () => db().post.create({ data: { authorId: 'nobody', title: 'Orphan', slug: 'orphan' } }),
            /Foreign key constraint/
        );
    });
});

describe('raw queries', () => {
    it('reads columns by name', async () => {
        // The regression this example was written for: prepared statements
        // once declared no columns, so every raw result came back positionally
        // and a lookup by name found nothing. Prisma Client hid it by mapping
        // on position from its own schema.
        const rows = await db().$queryRawUnsafe(
            "SELECT slug AS post_slug, views AS view_count FROM Post WHERE status = 'PUBLISHED'"
        );
        assert.equal(rows.length, 1);
        assert.deepEqual(Object.keys(rows[0]).sort(), ['post_slug', 'view_count']);
        assert.equal(rows[0].post_slug, 'on-the-analytical-engine');
    });

    it('runs the SQL an application writes by hand', async () => {
        const rows = await db().$queryRawUnsafe(`
            SELECT a.name AS author, COUNT(p.id) AS posts,
                   JSON_ARRAYAGG(p.status) AS statuses
            FROM Author a
            LEFT JOIN Post p ON p.authorId = a.id
            GROUP BY a.id, a.name
            ORDER BY a.name
        `);
        // The seeded pair. Isolation is per *file*, so an earlier test in this
        // one has already added an author — assert on what this test set up
        // rather than on the whole table.
        const seeded = rows.filter((r) => ['Ada Lovelace', 'Grace Hopper'].includes(r.author));
        assert.equal(seeded.length, 2);
        // A number, not the string "1": the engine declares COUNT as an
        // integer and the driver decodes it as one.
        assert.equal(typeof rows[0].posts, 'bigint');
    });
});
